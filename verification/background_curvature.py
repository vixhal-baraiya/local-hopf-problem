"""Check the Cheeger curvature table for (Z) in the verifier's longitude-height chart."""
import argparse
from itertools import combinations
from pathlib import Path

import sympy as sp

from full_metric_check import C, S, rational_in_cosine
from jets import K, cheeger, curvature, one, origin
from quadratic_coefficient import chart
from quadratic_lean import rows


def table():
    _, _, _, _, metric, inverse, _ = chart(C, S)
    raw = curvature(metric, inverse)
    # The curvature of g_CM = 2 g_t has twice the (0,4)-tensor of g_t.
    R = [[2 * entry.get(origin, K.zero) for entry in row] for row in raw]
    t = cheeger
    h = 1 + 2*t
    operator = [[h,0,0,0], [0,one,0,0], [0,0,1+t,t*C], [0,0,t*C,1+t]]
    pairs = list(combinations(range(4), 2))
    wedge = [[operator[i][k]*operator[j][l] - operator[i][l]*operator[j][k]
              for k,l in pairs] for i,j in pairs]
    def pull(i,j):
        return sum((wedge[k][i]*R[k][l]*wedge[l][j]
                    for k in range(6) for l in range(6) if wedge[k][i] and wedge[l][j]), K.zero)
    matrix = [[pull(i,j) for j in range(6)] for i in range(6)]
    a,b,c,d,e,f,g = [matrix[i][j] for i,j in [(1,4),(1,1),(1,2),(1,3),(3,3),(3,4),(5,5)]]
    assert matrix == [
        [0,0,0,0,0,2*a], [0,b,c,d,a,0], [0,c,b,-a,-d,0],
        [0,d,-a,e,f,0], [0,a,-d,f,e,0], [2*a,0,0,0,0,g],
    ]
    den = 2*h*((1+t)**2-(t*C)**2)
    T,U = sp.symbols("t u")
    return [rows(sp.cancel(rational_in_cosine(den*x)),T,U) for x in (a,b,c,d,e,f,g)]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write",action="store_true")
    args = parser.parse_args()
    target = Path(__file__).resolve().parents[1] / "lean/LocalHopf/BackgroundData.lean"
    values = ",\n   ".join(table())
    output = ("import LocalHopf.RationalBox\n\n"
        "/-! Denominator-cleared entries of the Cheeger curvature matrix after applying\n"
        "the inverse Cheeger endomorphism to both input vectors. Generated by\n"
        "`verification/background_curvature.py` from the metric two-jet. -/\n"
        "namespace LocalHopf.BackgroundGrowth\n\n"
        "def curvatureEntries : Fin 7 → Certificate.Coefficients :=\n  !["+values+"]\n\n"
        "end LocalHopf.BackgroundGrowth\n")
    if args.write:
        target.write_text(output,encoding="utf-8",newline="\n")
    elif target.read_text(encoding="utf-8") != output:
        raise SystemExit("BackgroundData.lean differs from the computed curvature")
    print("All 36 curvature entries agree, over Q(t,r).")


if __name__ == "__main__":
    main()
