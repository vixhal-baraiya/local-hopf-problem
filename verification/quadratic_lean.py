"""Export the fitted coefficients of Proposition 5.1. Use --write to regenerate QuadraticData.lean."""
import argparse
import json
from math import isqrt
from pathlib import Path

import sympy as sp


def rows(poly, t, u):
    poly = sp.Poly(poly, t, u, domain=sp.ZZ)
    result = []
    for i in range(poly.degree(t) + 1):
        row = [int(poly.nth(i, j)) for j in range(poly.degree(u) + 1)]
        while row and row[-1] == 0:
            row.pop()
        result.append(str(row))
    return "[" + ",\n     ".join(result) + "]"


def export(raw):
    t, u = sp.symbols("t u")
    h = 1 + 2*t
    src = {key: sp.sympify(val, locals={"t": t, "u": u})
           for key, val in raw.items() if "@" not in key}
    for side, profile in (("Fx", "aa"), ("Fy", "bb")):
        for kind in ("aa", "bb"):
            for order, expected in enumerate((0, 18*u/h**2, 18*(u**2-1)/h**2)):
                if sp.cancel(src[f"{side}_{kind}{order}"] - (expected if kind == profile else 0)) != 0:
                    raise ValueError(f"unexpected profile multiplier for {side}_{kind}{order}")
    if sp.cancel(src["Fx_base"] - src["Fy_base"].subs(u, -u)) != 0:
        raise ValueError("the x base channel is no longer the reflection of the y channel")
    weights = [sp.Rational(p, q) for p, q in
               [(2203841, 1920), (5579141, 153600), (214597, 103680),
                (48211, 307200), (251, 19200), (25, 165888)]]
    jet = sum(a*n**2*sp.chebyshevt(n, u) for n, a in enumerate(weights, 1))
    sqrt_lower = sp.Rational(isqrt(15*10**24), 10**12)
    fy_lower = src["Fy_base"] + 18/h**2*(jet + sp.Rational(42025, 36)*(sqrt_lower-15/(4-u)))
    out = ["import LocalHopf.RationalBox", "",
           "/-! Exact Horner data for the quadratic certificate, generated by",
           "`verification/quadratic_lean.py`. Rows index powers of t, entries powers of u. -/",
           "namespace LocalHopf.Certificate", ""]
    for name, expr in [("baseY", src["Fy_base"]), ("lowerY", fy_lower),
                       ("sc", src["Sc"]), ("n1", src["N1"]), ("n2", src["N2"])]:
        num, den = sp.fraction(sp.cancel(expr))
        if den.subs({t: 0, u: 0}) < 0:
            num, den = -num, -den
        out.extend([f"def {name} : Quotient :=", "  ⟨" + rows(num,t,u) + ",",
                    "   " + rows(den,t,u) + "⟩", ""])
    r = sp.Symbol("r")
    cos_r, sin_r = (1-r**2)/(1+r**2), 2*r/(1+r**2)
    plus, minus = 1+t+t*u, 1+t-t*u
    groups = [
        ("vectorNum", ("A0", "A1", "B0", "B1"), (False, True, False, True), 40*h**2*(plus*minus)**2),
        ("matrix1Num", ("M100", "M101", "M110", "M111"), (False, True, True, False), 4*h*(plus*minus)**2),
        ("matrix2Num", ("M200", "M201", "M211"), (False, True, False), 4*h*(plus*minus)**3),
    ]
    for name, keys, parity, den in groups:
        entries = []
        for key, odd in zip(keys, parity, strict=True):
            value = sp.sympify(raw[key + ("@sin" if odd else "@u")])
            actual = sp.sympify(raw[key + "@r"])
            if sp.cancel(value.subs(u, cos_r)*(sin_r if odd else 1)-actual) != 0:
                raise ValueError(f"{key} disagrees with the fitted half-angle coefficient")
            entries.append(rows(sp.cancel(value*den), t, u))
        out.extend([f"def {name} : Fin {len(keys)} → Coefficients :=",
                    "  ![" + ",\n   ".join(entries) + "]", ""])
    out.append("end LocalHopf.Certificate")
    return "\n".join(out) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()
    here = Path(__file__).resolve().parent
    target = here.parent / "lean/LocalHopf/QuadraticData.lean"
    output = export(json.loads((here / "data/quadratic_coefficients.json").read_text()))
    if args.write:
        target.write_text(output, encoding="utf-8", newline="\n")
    elif output != target.read_text(encoding="utf-8"):
        raise SystemExit("QuadraticData.lean differs from the quadratic export")
    print("QuadraticData.lean matches the scalar, vector and matrix exports")


if __name__ == "__main__":
    main()
