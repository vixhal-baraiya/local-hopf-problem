"""Compute the entire equatorial rotation orbit over Q(t,r,a).

Here r = tan((beta-alpha)/2), and a is the half-angle parameter for rotating
the axes in the normalized frame. A numerator of degree at most six over
(1+a²)³ has Fourier degree at most three. Compare the resulting integer coefficients
with the input to Lean. Pass --write to regenerate EquatorJetData.lean.
"""

import argparse
import os
from pathlib import Path

import sympy as sp


def lean_table(cubic):
    t, r, a = sp.symbols("t r a")
    h = 1 + 2*t
    den = 10000*h**2*(1+r**2)**5*(h+r**2)**2*(1+h*r**2)**2
    poly = sp.Poly(sp.cancel(cubic*den*(1+a**2)**3), a, r, t, domain=sp.ZZ)
    assert poly.degree(a) <= 6 and poly.degree(r) <= 18
    rows = []
    for i in range(7):
        row = []
        for j in range(19):
            cs = [int(poly.coeff_monomial((i, j, k))) for k in range(poly.degree(t)+1)]
            while cs and cs[-1] == 0:
                cs.pop()
            row.append(str(cs))
        rows.append("    [" + ",\n     ".join(row) + "]")
    return ("/-! Integer coefficients of the equatorial cubic numerator. Generated by\n"
            "`verification/equator_rotation.py`. Indices are rotation degree, separation\n"
            "degree, and increasing powers of the Cheeger parameter. -/\n"
            "namespace LocalHopf.EquatorJet\n\n"
            "def data : Fin 7 → List (List ℤ) :=\n  ![\n"
            + ",\n".join(rows) + "]\n\nend LocalHopf.EquatorJet\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true")
    opts = parser.parse_args()
    if not __debug__:
        parser.error("run without -O to enable the assertions used by the curvature checks")
    os.environ["HOPF_BACKEND"] = "flint-rotation"
    from flint_field import K
    from full_metric_check import cubic_task, FMODES
    a = K.gens[2]
    c, s = (1-a*a)/(1+a*a), 2*a/(1+a*a)
    rotation = ((c, -s, 0), (s, c, 0), (0, 0, 1))
    quadratic, cubic = cubic_task((rotation, "full"))
    assert quadratic == 0, "nonzero quadratic coefficient on the equator"
    result = "import Mathlib.Data.Fin.VecNotation\n\n" + lean_table(cubic)
    print("Full rotation computed. Cleared numerator has rotation degree at most six.", flush=True)
    # At cubic order the second metric coefficient enters linearly. Test each
    # of the six independent profile jets against the same zero-profile baseline.
    base = cubic_task((rotation, "zero"))
    for mode in FMODES:
        assert cubic_task((rotation, mode)) == base, mode
        print(f"{mode}: zero quadratic and cubic response at every rotation", flush=True)
    dest = Path(__file__).resolve().parents[1] / "lean" / "LocalHopf" / "EquatorJetData.lean"
    if opts.write:
        dest.write_text(result, encoding="utf-8", newline="\n")
    elif dest.read_text(encoding="utf-8") != result:
        raise ValueError(f"{dest.name} differs from the exact curvature calculation")
    print("Equatorial curvature coefficients match the Lean table.", flush=True)


if __name__ == "__main__":
    main()
